// tests/pwa-icons.test.ts
// Guards the mobile app icon surface: an installed PWA must not show white
// borders around the logo when the launcher masks the icon square.
//
// WHAT IS GUARDED
//   - Every manifest icon exists at its declared size.
//   - Every icon is fully opaque. Mobile launchers and iOS apply their own
//     mask; transparent or white padding reads as a border ring.
//   - Every icon corner is dark navy. A white corner is the exact regression
//     that shipped once (assets-generator flattens maskable/apple icons on
//     white with 30% padding by default).
//   - The maskable icon has no bright pixels outside the 80%-diameter safe
//     circle, so any launcher mask (circle, squircle, rounded square) trims
//     only background, never artwork.
//
// The icons are committed under public/ and regenerated by `npm run pwa:assets`
// (part of `npm run build`), so these assertions run against the real files the
// browser and the OS receive.

import { existsSync, statSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import sharp from 'sharp';

const ICON_DIR = resolve('public/assets/images/new-logo');

const EDGE_INSET = 2;
const MAX_EDGE_LUMA = 80;
const MAX_TRIM_ZONE_LUMA = 190;
const SAFE_CIRCLE_RATIO = 0.4; // radius of the 80%-diameter safe circle

interface RawImage {
  readonly width: number;
  readonly height: number;
  readonly channels: number;
  readonly data: Buffer;
}

async function readRaw(file: string): Promise<RawImage> {
  const { data, info } = await sharp(resolve(ICON_DIR, file))
    .raw()
    .toBuffer({ resolveWithObject: true });
  return { width: info.width, height: info.height, channels: info.channels, data };
}

function luma(image: RawImage, x: number, y: number): number {
  const index = (y * image.width + x) * image.channels;
  return 0.2126 * image.data[index] + 0.7152 * image.data[index + 1] + 0.0722 * image.data[index + 2];
}

function minAlpha(image: RawImage): number {
  if (image.channels < 4) return 255;
  let min = 255;
  for (let index = 3; index < image.data.length; index += image.channels) {
    min = Math.min(min, image.data[index]);
  }
  return min;
}

function perimeterIsDark(image: RawImage): boolean {
  const xs = [0, 1, image.width - 2, image.width - 1];
  const ys = [0, 1, image.height - EDGE_INSET, image.height - 1];
  for (let x = 0; x < image.width; x += 1) {
    for (const y of ys) {
      if (luma(image, x, y) >= MAX_EDGE_LUMA) return false;
    }
  }
  for (let y = 0; y < image.height; y += 1) {
    for (const x of xs) {
      if (luma(image, x, y) >= MAX_EDGE_LUMA) return false;
    }
  }
  return true;
}

function maxLumaOutsideSafeCircle(image: RawImage): number {
  const cx = image.width / 2;
  const cy = image.height / 2;
  const safeRadius = image.width * SAFE_CIRCLE_RATIO;
  let max = 0;
  for (let y = 0; y < image.height; y += 1) {
    for (let x = 0; x < image.width; x += 1) {
      if (Math.hypot(x - cx, y - cy) < safeRadius) continue;
      max = Math.max(max, luma(image, x, y));
    }
  }
  return max;
}

const MANIFEST_ICONS = [
  { file: 'pwa-64x64.png', size: 64 },
  { file: 'pwa-192x192.png', size: 192 },
  { file: 'pwa-512x512.png', size: 512 },
  { file: 'maskable-icon-512x512.png', size: 512 },
  { file: 'apple-touch-icon-180x180.png', size: 180 },
] as const;

describe('pwa icons', () => {
  it('ships the full-bleed icon master', async () => {
    const file = resolve(ICON_DIR, 'icon-master.png');
    expect(existsSync(file)).toBe(true);

    const image = await readRaw('icon-master.png');
    expect(image.width).toBe(1024);
    expect(image.height).toBe(1024);
    expect(minAlpha(image)).toBe(255);
    expect(perimeterIsDark(image)).toBe(true);
    expect(maxLumaOutsideSafeCircle(image)).toBeLessThan(MAX_TRIM_ZONE_LUMA);
  });

  it.each(MANIFEST_ICONS)('$file exists at $size x $size', async ({ file, size }) => {
    expect(existsSync(resolve(ICON_DIR, file))).toBe(true);

    const image = await readRaw(file);
    expect(image.width).toBe(size);
    expect(image.height).toBe(size);
  });

  it.each(MANIFEST_ICONS)('$file is opaque with no white border', async ({ file }) => {
    const image = await readRaw(file);

    expect(minAlpha(image)).toBe(255);
    expect(perimeterIsDark(image)).toBe(true);
  });

  it('ships a maskable icon whose artwork stays inside the safe circle', async () => {
    const image = await readRaw('maskable-icon-512x512.png');
    expect(maxLumaOutsideSafeCircle(image)).toBeLessThan(MAX_TRIM_ZONE_LUMA);
  });

  it('ships a non-empty favicon', () => {
    const file = resolve(ICON_DIR, 'favicon.ico');
    expect(existsSync(file)).toBe(true);
    expect(statSync(file).size).toBeGreaterThan(0);
  });
});
